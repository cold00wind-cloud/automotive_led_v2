#pragma once
/*
 * Критична секція — шматок коду, який не можна перервати перериванням.
 *
 * Навіщо: головний цикл і ISR (переривання) працюють з одними й тими самими
 * змінними (черга подій, програмні таймери, регістр EXTI->IMR). Якщо ISR
 * вклиниться посеред "прочитай-зміни-запиши", дані зіпсуються.
 *
 * Чому зберігаємо PRIMASK, а не просто вмикаємо переривання назад:
 * функцію можуть викликати і з ISR, і з коду, де переривання вже вимкнені.
 * Ми повертаємо рівно той стан, який був до входу — так секції можна вкладати.
 */
#include "stm32f4xx_hal.h"

static inline uint32_t critical_enter(void)
{
    uint32_t primask = __get_PRIMASK();
    __disable_irq();
    return primask;
}

static inline void critical_exit(uint32_t primask)
{
    __set_PRIMASK(primask);
}
