#pragma once
/*
 * Черга подій (FIFO, кільцевий буфер).
 *
 * Це ЄДИНЕ місце, куди пишуть і переривання, і головний цикл. Тому всі
 * операції загорнуті в критичну секцію (див. critical.h). Усі інші стани
 * (кнопки, LED, логіка авто) змінює тільки головний цикл — одна точка запису,
 * гонок немає.
 */
#include <stdbool.h>
#include <stdint.h>
#include "dl/event.h"

#define EQ_CAPACITY 16u

/* Покласти подію. Можна з ISR. Повертає false, якщо черга повна (подію втрачено). */
bool eq_post(Event e);

/* Дістати найстарішу подію. Повертає false, якщо черга порожня. */
bool eq_pop(Event *out);

bool eq_is_empty(void);

/* Скільки подій загубилося через переповнення. Має бути 0 — інакше збільш EQ_CAPACITY. */
uint32_t eq_overflow_count(void);
