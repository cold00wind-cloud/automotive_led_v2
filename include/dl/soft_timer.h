#pragma once
/*
 * Програмні таймери: один апаратний таймер (SysTick, 1 мс) → багато логічних.
 *
 * Кожен таймер — це лічильник у RAM. st_tick() (з SysTick_Handler) зменшує
 * лічильники; коли якийсь дійшов до нуля — кладе в чергу SIG_TIMEOUT.
 * Компонент не чекає і не перевіряє час сам — він просто отримає подію.
 *
 * "Покоління" (tag): коли таймер перезапускають або зупиняють, його
 * покоління збільшується. Подія SIG_TIMEOUT несе покоління, з яким таймер
 * спрацював. Якщо подія вже лежала в черзі, а таймер тим часом перезапустили,
 * st_is_current() скаже false — це "застаріла" подія, її треба викинути.
 */
#include <stdbool.h>
#include <stdint.h>

#define ST_MAX_TIMERS 16u

/* Запустити (або перезапустити) таймер id на ms мілісекунд.
 * periodic = true → після спрацювання стартує знову з тим самим періодом. */
void st_start(uint8_t id, uint32_t ms, bool periodic);

void st_stop(uint8_t id);

/* Чи подія SIG_TIMEOUT з таким tag ще актуальна для таймера id. */
bool st_is_current(uint8_t id, uint8_t tag);

/* Викликати РІВНО раз на 1 мс з SysTick_Handler. */
void st_tick(void);
